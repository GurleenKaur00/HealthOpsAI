-- Query 1: Top 10 Hospitals by Total Admissions
SELECT

    h.name AS hospital_name,

    COUNT(*) AS total_admissions

FROM admissions a

JOIN hospitals h
ON a.hospital_id = h.hospital_id

GROUP BY h.name

ORDER BY total_admissions DESC

LIMIT 10;

-- Query 2: Readmission Rate by Hospital
SELECT

    h.name AS hospital_name,

    ROUND(AVG(a.readmitted_30d) * 100, 2)
        AS readmission_rate

FROM admissions a

JOIN hospitals h
ON a.hospital_id = h.hospital_id

GROUP BY h.name

ORDER BY readmission_rate DESC;

-- Query 3: Average Length of Stay by Hospital
SELECT

    h.name,

    ROUND(AVG(a.los_days),2)
        AS average_los

FROM admissions a

JOIN hospitals h
ON a.hospital_id = h.hospital_id

GROUP BY h.name

ORDER BY average_los DESC;

-- Query 4: Total Revenue Generated by Hospital
SELECT

    h.name,

    ROUND(SUM(b.total_cost_inr),2)
        AS total_revenue

FROM admissions a

JOIN hospitals h
ON a.hospital_id = h.hospital_id

JOIN billing b
ON a.admission_id = b.admission_id

GROUP BY h.name

ORDER BY total_revenue DESC;

