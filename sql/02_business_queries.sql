-- Query 19: Monthly Admission Trend
SELECT

    strftime('%Y-%m', admit_date)
        AS month,

    COUNT(*) AS admissions

FROM admissions

GROUP BY month

ORDER BY month;

-- Query 20: Monthly Revenue Trend
SELECT

    strftime('%Y-%m', a.admit_date)
        AS month,

    ROUND(SUM(b.total_cost_inr),2)
        AS revenue

FROM admissions a

JOIN billing b
ON a.admission_id = b.admission_id

GROUP BY month

ORDER BY month;